"""Publication figures for the TELMED 2027 paper (IEEE two-column, column width 3.5 in).

    python paper/figures/make_figures.py

Fig. 1  referral pathway and the four places the patient note can be read
Fig. 2  SPLIT-Match architecture (cloud / clinic laptop, privacy gateway)
Fig. 3  missed eligible patients vs unnecessary referrals (per 100 patients)

Every plotted number is read from paper/generated/numbers.tex (generated by
experiments/paper_numbers.py). Output: vector PDF (for LaTeX) and 600-dpi PNG (for Word).
Fonts: Times New Roman, 7-8 pt, matching IEEE body/caption sizes.
"""
import re
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import FancyBboxPatch, FancyArrowPatch, Rectangle  # noqa: E402

HERE = Path(__file__).resolve().parent
NUMS = HERE.parent / "generated" / "numbers.tex"
COL_W = 3.45  # inches; IEEE column is ~3.49 in

plt.rcParams.update({
    "font.family": "serif",
    "font.serif": ["Times New Roman", "Times", "DejaVu Serif"],
    "mathtext.fontset": "stix",
    "font.size": 7.5,
    "axes.labelsize": 7.5,
    "axes.titlesize": 7.5,
    "xtick.labelsize": 7,
    "ytick.labelsize": 7,
    "legend.fontsize": 6.5,
    "axes.linewidth": 0.6,
    "xtick.major.width": 0.6,
    "ytick.major.width": 0.6,
    "pdf.fonttype": 42,
    "savefig.dpi": 600,
})

# Okabe-Ito colour-blind-safe palette; each level also has its own marker shape
C_FULL, C_REC, C_FACT, C_NONE = "#0072B2", "#E69F00", "#D55E00", "#009E73"
C_CLOUD_BG, C_EDGE_BG, C_LINE = "#EAF2FA", "#E8F5EF", "#333333"


def macros():
    d = {}
    for line in NUMS.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}\s*$", line)
        if m:
            d[m.group(1)] = m.group(2)
    return d


M = macros()


def num(k):
    return float(M[k].replace("\\%", "").replace(",", ""))


def save(fig, name):
    for ext in ("pdf", "png"):
        fig.savefig(HERE / f"{name}.{ext}", bbox_inches="tight", pad_inches=0.02)
    plt.close(fig)
    print("wrote", name)


def box(ax, x, y, w, h, text, fc="white", ec=C_LINE, lw=0.7, fs=6.8, bold=False, r=0.012):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle=f"round,pad=0,rounding_size={r}",
                                fc=fc, ec=ec, lw=lw, zorder=3))
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=fs, zorder=4,
            fontweight="bold" if bold else "normal", linespacing=1.15)


def arrow(ax, p, q, ls="-", lw=0.8, color=C_LINE, ms=7, cs="arc3"):
    ax.add_patch(FancyArrowPatch(p, q, arrowstyle="-|>", mutation_scale=ms, lw=lw, ls=ls,
                                 color=color, connectionstyle=cs, shrinkA=0, shrinkB=0, zorder=2))


# ─────────────────────────────── Fig. 1: pathway + privacy levels
def fig_pathway():
    fig = plt.figure(figsize=(COL_W, 2.1))
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.axis("off")

    # (a) referral pathway
    ax.text(0.0, 0.975, "(a) Telemedicine referral pathway", fontsize=7.2, fontweight="bold", va="top")
    ys, h, w = 0.745, 0.15, 0.22
    xs = [0.0, 0.26, 0.52, 0.78]
    labels = ["Patient visit\n(district health\ncentre)", "Pre-screen on\nclinic laptop\n(health worker)",
              "Referral by\nteleconsultation", "Full screening\nat trial site"]
    for i, (x, t) in enumerate(zip(xs, labels)):
        box(ax, x, ys, w, h, t, fc="#F4F4F4" if i != 1 else "#FFF4D6")
        if i:
            arrow(ax, (xs[i - 1] + w, ys + h / 2), (x, ys + h / 2))
    ax.text(0.65, ys + h + 0.012, "likely eligible", fontsize=6.5, ha="center", style="italic")
    # error asymmetry
    ax.text(0.37, ys - 0.045, "Two errors are possible at the pre-screen:", fontsize=6.4, ha="center")
    ax.text(0.37, ys - 0.095, "unnecessary referral \u2192 corrected at the site (one teleconsultation)",
            fontsize=6.4, ha="center", color="#555555")
    ax.text(0.37, ys - 0.145, "missed eligible patient \u2192 never referred (final)",
            fontsize=6.4, ha="center", color=C_FACT, fontweight="bold")

    # (b) what the cloud receives
    ax.text(0.0, 0.535, "(b) What the cloud receives about the patient", fontsize=7.2, fontweight="bold", va="top")
    rows = [("Full note", "Cloud LLM reads the full note", C_FULL),
            ("De-identified record", "Cloud LLM reads a record extracted on the laptop", C_REC),
            ("Single facts", "SPLIT-Match: one minimal fact per cloud query (Fig. 2)", C_FACT),
            ("Nothing", "Model reads the note on the laptop; SPLIT-Match offline", C_NONE)]
    y0, rh, gap = 0.37, 0.078, 0.018
    for i, (lev, sysd, c) in enumerate(rows):
        y = y0 - i * (rh + gap)
        ax.add_patch(Rectangle((0.0, y), 0.255, rh, fc=c, ec="none", alpha=0.9, zorder=3))
        ax.text(0.128, y + rh / 2, lev, ha="center", va="center", fontsize=6.6, color="white",
                fontweight="bold", zorder=4)
        ax.add_patch(Rectangle((0.265, y), 0.655, rh, fc="white", ec=c, lw=0.7, zorder=3))
        ax.text(0.275, y + rh / 2, sysd, ha="left", va="center", fontsize=6.5, zorder=4)
    ytop, ybot = y0 + rh, y0 - 3 * (rh + gap)
    arrow(ax, (0.96, ytop), (0.96, ybot), lw=0.9, ms=8)
    ax.text(0.985, (ytop + ybot) / 2, "more privacy", rotation=270, ha="center", va="center", fontsize=6.4)
    save(fig, "fig1_pathway")


# ─────────────────────────────── Fig. 2: SPLIT-Match architecture
def fig_architecture():
    fig = plt.figure(figsize=(COL_W, 2.45))
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.axis("off")

    lx, rx, w = 0.03, 0.555, 0.415
    # lanes
    ax.add_patch(FancyBboxPatch((0.005, 0.03), 0.47, 0.885, boxstyle="round,pad=0,rounding_size=0.02",
                                fc=C_CLOUD_BG, ec="#7FA7CF", lw=0.7, zorder=1))
    ax.add_patch(FancyBboxPatch((0.525, 0.03), 0.47, 0.885, boxstyle="round,pad=0,rounding_size=0.02",
                                fc=C_EDGE_BG, ec="#73B596", lw=0.7, zorder=1))
    ax.text(0.24, 0.95, "Cloud (public side)", ha="center", fontsize=7.4, fontweight="bold")
    ax.text(0.76, 0.95, "Clinic laptop (private side)", ha="center", fontsize=7.4, fontweight="bold")
    # gateway
    ax.plot([0.5, 0.5], [0.04, 0.905], ls=(0, (3, 2)), lw=0.9, color=C_FACT, zorder=2)
    ax.text(0.5, 0.715, "privacy gateway", rotation=90, ha="center", va="center", fontsize=6.5,
            color=C_FACT, bbox=dict(fc="white", ec="none", pad=0.6), zorder=5)

    h = 0.125
    ycl = [0.745, 0.545, 0.345, 0.115]
    box(ax, lx, ycl[0], w, h, "Trial criteria\n(public text)")
    box(ax, lx, ycl[1], w, h, "Two compilers: gpt-oss-120b\nand Qwen3.8-27B")
    box(ax, lx, ycl[2], w, h, "Typed three-valued\ncriteria program")
    box(ax, lx, ycl[3], w, h, "Cloud judge (L2)\nsees one fact only")
    for a, b in ((0, 1), (1, 2)):
        arrow(ax, (lx + w / 2, ycl[a]), (lx + w / 2, ycl[b] + h))
    ax.text(lx + w / 2 - 0.012, (ycl[1] + ycl[2] + h) / 2, "kept only if\nboth agree", fontsize=6.3,
            ha="right", va="center", style="italic", color="#444444")

    yr = [0.745, 0.545, 0.345, 0.115]
    box(ax, rx, yr[0], w, h, "Patient note\n(never leaves)")
    box(ax, rx, yr[1], w, h, "Fact extractor (Qwen3-4B)\n+ rule-based checker")
    box(ax, rx, yr[2], w, h, "Rules: true / false / unknown;\nexclusion needs two keys")
    box(ax, rx, yr[3], w, h, "Laptop judge (L1) \u2192\nEligible / Not / Ask / Defer",
        fc="#FFF4D6")
    for a, b in ((0, 1), (1, 2), (2, 3)):
        arrow(ax, (rx + w / 2, yr[a]), (rx + w / 2, yr[b] + h))
    # crossings
    arrow(ax, (lx + w, ycl[2] + h / 2), (rx, yr[2] + h / 2), lw=0.9)
    ax.text(0.5, ycl[2] + h + 0.038, "program, once per trial", fontsize=6.3, ha="center",
            bbox=dict(fc="white", ec="none", pad=0.4), zorder=6)
    arrow(ax, (rx, yr[3] + 0.085), (lx + w, ycl[3] + 0.085), lw=0.8, ls=(0, (2.5, 1.5)), color=C_FACT)
    arrow(ax, (lx + w, ycl[3] + 0.035), (rx, yr[3] + 0.035), lw=0.8, ls=(0, (2.5, 1.5)), color=C_FACT)
    ax.text(0.5, 0.06, "residual criterion + one fact out, answer back", fontsize=6.3, ha="center",
            color=C_FACT, bbox=dict(fc="white", ec="none", pad=0.4), zorder=6)
    save(fig, "fig2_splitmatch")


# ─────────────────────────────── Fig. 3: missed vs unnecessary
def fig_frontier():
    fig, ax = plt.subplots(figsize=(COL_W, 2.12))
    per100 = lambda c: c / 45 * 100  # noqa: E731  (45 test patients)
    pts = [
        ("Cloud LLM, full note", num("unrefHundredCloudZS"), num("missHundredCloudZS"), C_FULL, "o", True),
        ("Cloud LLM, laptop record", num("unrefHundredRecDeploy"), num("missHundredRecDeploy"), C_REC, "s", True),
        ("SPLIT-Match, facts", num("unrefHundredSplitDeploy"), num("missHundredSplitDeploy"), C_FACT, "^", True),
        ("SPLIT-Match, offline (proxy)", num("unrefHundredOffline"), num("missHundredOffline"), C_NONE, "D", False),
        ("Qwen3-4B on laptop", num("unrefHundredEdgeFourB"), num("missHundredEdgeFourB"), C_NONE, "D", True),
        ("gpt-oss-20b on laptop", num("locFullUnrefHundred"), num("locFullMissHundred"), C_NONE, "D", True),
    ]
    # cloud run-to-run range (five runs)
    cx0, cx1 = per100(num("cloudRunsUnnMin")), per100(num("cloudRunsUnnMax"))
    cy0, cy1 = num("cloudRunsMissHundredMin"), num("cloudRunsMissHundredMax")
    ax.add_patch(Rectangle((cx0, cy0), cx1 - cx0, cy1 - cy0, fc=C_FULL, alpha=0.13, ec=C_FULL, lw=0.5,
                           ls="--", zorder=1))
    offs = {"Cloud LLM, full note": (6, -9, "left"), "Cloud LLM, laptop record": (6, 2, "left"),
            "SPLIT-Match, facts": (6, 3, "left"), "SPLIT-Match, offline (proxy)": (-6, -8, "right"),
            "Qwen3-4B on laptop": (6, 3, "left"), "gpt-oss-20b on laptop": (5, -9, "left")}
    for lab, x, y, c, mk, filled in pts:
        ax.scatter([x], [y], s=26, marker=mk, facecolor=c if filled else "white", edgecolor=c, lw=1.0, zorder=4)
        dx, dy, ha = offs[lab]
        ax.annotate(lab, (x, y), xytext=(dx, dy), textcoords="offset points", fontsize=6.3, ha=ha, va="center")
    ax.text(cx0 - 1.0, cy1 + 1.0, "cloud,\n5 runs", fontsize=6.3, color=C_FULL, ha="right", va="bottom")
    # Qwen3-1.7B is off scale
    x17, y17 = num("unrefHundredQwenOneSeven"), num("missHundredQwenOneSeven")
    ax.annotate(f"Qwen3-1.7B on laptop:\n{x17:.0f} unnecessary (off scale)", xy=(126, y17), xytext=(124, 6), fontsize=6.4,
                ha="right", va="center", color=C_NONE,
                arrowprops=dict(arrowstyle="-|>", lw=0.6, color=C_NONE, mutation_scale=6))
    ax.set_xlim(0, 126)
    ax.set_ylim(0, 72)
    ax.set_xlabel("Unnecessary referrals per 100 patients (corrected at the site)")
    ax.set_ylabel("Missed eligible per 100 patients\n(never referred)")
    ax.spines[["top", "right"]].set_visible(False)
    ax.grid(True, lw=0.3, color="#DDDDDD", zorder=0)
    ax.annotate("better", xy=(1.5, 1.5), xytext=(8, 6.5), fontsize=6.5, color="#666666",
                arrowprops=dict(arrowstyle="-|>", lw=0.6, color="#666666", mutation_scale=6))
    from matplotlib.lines import Line2D
    leg = [Line2D([], [], marker="o", ls="", color=C_FULL, label="full note", ms=4),
           Line2D([], [], marker="s", ls="", color=C_REC, label="record", ms=4),
           Line2D([], [], marker="^", ls="", color=C_FACT, label="facts", ms=4),
           Line2D([], [], marker="D", ls="", color=C_NONE, label="nothing", ms=4)]
    ax.legend(handles=leg, title="Cloud receives", title_fontsize=6.3, loc="upper right",
              bbox_to_anchor=(1.0, 0.86), frameon=False, handletextpad=0.2, borderaxespad=0.2)
    save(fig, "fig3_missed_vs_unnecessary")


# ─────────────────────────────── Fig. 4: both errors and device time per configuration
def fig_device_cost():
    import numpy as np
    from matplotlib.patches import Patch
    fig, ax = plt.subplots(figsize=(COL_W, 2.1))
    per100 = lambda c: c / 45 * 100  # noqa: E731  (45 test patients)
    groups = [
        ("Cloud LLM\n(network)", num("missHundredCloudZS"), num("unrefHundredCloudZS"), C_FULL,
         (num("cloudRunsMissHundredMin"), num("cloudRunsMissHundredMax")),
         (per100(num("cloudRunsUnnMin")), per100(num("cloudRunsUnnMax")))),
        (f"Qwen3-1.7B\n{num('capOneSevenLat'):.0f} s", num("missHundredQwenOneSeven"),
         num("unrefHundredQwenOneSeven"), C_NONE, None, None),
        (f"Qwen3-4B\n{num('capFourLat'):.0f} s", num("missHundredEdgeFourB"), num("unrefHundredEdgeFourB"),
         C_NONE, None, None),
        (f"gpt-oss-20b\n{num('locFullLatMed'):.0f} s", num("locFullMissHundred"), num("locFullUnrefHundred"),
         C_NONE, None, None),
        (f"SPLIT-Match\n{num('edgeSplitPerPatient') / 6:.0f} s", num("missHundredSplitDeploy"),
         num("unrefHundredSplitDeploy"), C_FACT, None, None),
    ]
    ymax = 100
    x = np.arange(len(groups))
    w = 0.36
    for k, (lab, miss, unn, c, mr, ur) in enumerate(groups):
        ax.bar(k - w / 2, miss, w, color=c, edgecolor=c, lw=0.6, zorder=3)
        ax.bar(k + w / 2, min(unn, ymax), w, color="white", edgecolor=c, lw=0.9, hatch="////", zorder=3)
        ax.text(k - w / 2, (mr[1] if mr else miss) + 1.5, f"{miss:.0f}", ha="center", va="bottom", fontsize=6.3)
        if unn > ymax:
            ax.text(k + w / 2, ymax + 1.5, f"{unn:.0f} (off scale)", ha="center", va="bottom", fontsize=6.3,
                    color=c, clip_on=False)
        else:
            ax.text(k + w / 2, (ur[1] if ur else unn) + 1.5, f"{unn:.0f}", ha="center", va="bottom", fontsize=6.3)
        if mr:
            ax.errorbar(k - w / 2, miss, yerr=[[miss - mr[0]], [mr[1] - miss]], fmt="none", ecolor="black",
                        elinewidth=0.6, capsize=1.6, zorder=4)
            ax.errorbar(k + w / 2, unn, yerr=[[unn - ur[0]], [max(ur[1] - unn, 0)]], fmt="none", ecolor="black",
                        elinewidth=0.6, capsize=1.6, zorder=4)
    ax.set_xticks(x)
    ax.set_xticklabels([g[0] for g in groups], fontsize=6.3)
    ax.set_ylim(0, ymax)
    ax.set_ylabel("Per 100 patients")
    ax.spines[["top", "right"]].set_visible(False)
    ax.grid(True, axis="y", lw=0.3, color="#DDDDDD", zorder=0)
    leg = [Patch(facecolor="#555555", edgecolor="#555555", label="missed eligible (final)"),
           Patch(facecolor="white", edgecolor="#555555", hatch="////", label="unnecessary referral (site corrects)")]
    ax.legend(handles=leg, loc="lower center", bbox_to_anchor=(0.5, 1.04), ncol=2, frameon=False, handlelength=1.2,
              borderaxespad=0.0, columnspacing=1.0)
    save(fig, "fig4_device_cost")


if __name__ == "__main__":
    fig_pathway()
    fig_architecture()
    fig_frontier()
    fig_device_cost()
